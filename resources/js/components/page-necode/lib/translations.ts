export function getTranslation(language: "id" | "en", key: string): string {
  const keys = key.split(".")
  let value: any = translations[language]

  for (const k of keys) {
    if (value && typeof value === "object") {
      value = value[k]
    } else {
      return key
    }
  }

  return typeof value === "string" ? value : key
}
